"use client";

import { useEffect, useState } from "react";
import { useParams, useRouter } from "next/navigation";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { ArrowLeft, Download, Loader2, PrinterIcon, Sparkles, User } from "lucide-react";
import { Separator } from "@/components/ui/separator";
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle, DialogTrigger } from "@/components/ui/dialog";
import { Label } from "@/components/ui/label";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { toast } from "sonner";
import InvoiceCard, { InvoiceHTML } from "@/components/InvoiceCard";

export default function InvoiceDetailsPage() {
  const { id } = useParams();
  const router = useRouter();
  const [invoice, setInvoice] = useState<any>(null);
  const [loading, setLoading] = useState(true);
    const [form,setForm] = useState({
        amount:0,
        paymentMethod:"",
        receiptNumber:"",
        notes:"",
        status:"paid",
        invoiceId:"",
        studentId:""
    })
const [paymentSubmittionLoading,setPaymentSubmittionLoading] = useState(false)
  useEffect(() => {
    fetch(`/api/admin/invoices/${id}`)
      .then((r) => r.json())
      .then((d) => {
        setInvoice(d);
        setForm({...form,invoiceId:d.id,studentId:d.student.id,amount:d.amount})
        console.log(d);
        
        setLoading(false);
      });
  }, [id]);

  const getBadge = (status: string) => {
    if (status === "paid") return <Badge className="bg-green-600">{status}</Badge>;
    if (status === "overdue")
      return <Badge className="bg-red-600">{status}</Badge>;
    return <Badge className="bg-yellow-500">{status}</Badge>;
  };

  if (loading)
    return (
      <div className="flex justify-center p-10">
        <Loader2 className="animate-spin" />
      </div>
    );

  if (!invoice) return <p className="p-6">Invoice not found</p>;

  //   const statusColor =
  //     paymentStatus === "Paid"
  //       ? "bg-green-100 text-green-700"
  //       : paymentStatus === "Overdue"
  //         ? "bg-red-100 text-red-700"
  //         : "bg-blue-100 text-blue-700"

  const invoiceDate = new Date(invoice.invoiceYear, invoice.invoiceMonth - 1);
  const monthName = invoiceDate.toLocaleString("default", {
    month: "long",
    year: "numeric",
  });

  const invoiceContent = `
═════════════════════════════════════════════════
                      INVOICE
═════════════════════════════════════════════════

Invoice #: ${invoice.invoiceNumber}
Date: ${invoiceDate.toLocaleDateString("en-PK")}
Due Date: ${new Date(invoice.dueDate).toLocaleDateString("en-PK")}

BILL TO:
Full name: ${invoice.student.firstName} ${invoice.student.lastName}
Email: ${invoice.student.email}
Phone: ${invoice.student.phone}
Room: ${invoice.student?.room?.roomNumber} (${invoice.student?.room?.roomType}) - ${
    invoice.student?.room?.floor
  } Floor

BILL BY  
HOSTEL : ${invoice.hostel.name}
ADDRESS : ${invoice.hostel.address}
CONTACT : ${invoice.hostel.phone} - ${invoice.hostel.email}

INVOICE DETAILS:
Description                         Amount
Monthly Hostel Rent (${monthName})  Rs ${invoice.amount.toLocaleString()}

═════════════════════════════════════════════════
TOTAL AMOUNT DUE:                    Rs ${invoice.amount.toLocaleString()}
═════════════════════════════════════════════════
PAYMENTS 
STATUS: ${invoice.status}
${invoice.status.toUpperCase()} RS ${invoice?.payments[0]?.amount.toLocaleString()}
${
  invoice.status === "paid"
    ? `Paid Date: ${new Date().toLocaleDateString("en-PK")}`
    : ""
}


          Thank you for your business!
            Generated by hostelhub.pk 
    `;



  const handleDownloadInvoice = () => {
    const element = document.createElement("a");
    element.setAttribute(
      "href",
      "data:text/plain;charset=utf-8," + encodeURIComponent(invoiceContent)
    );
    element.setAttribute("download", `${invoice.invoiceNumber}.txt`);
    element.style.display = "none";
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  const handlePrint = () => {
    if (typeof window !== undefined) {
      const printWindow = window.open("", "", "width=1000,height=800");

      printWindow?.document.write(`
    
        ${InvoiceHTML({invoice})}
     
  `);

      printWindow?.document.close();
      printWindow?.focus();
      printWindow?.print();

      // Optional auto-close after printing
      setTimeout(() => {
        printWindow?.close();
      }, 500);
    }
  };


  const handlePaymentUpdation = async() =>{
    try {
        setPaymentSubmittionLoading(true)
        let res = await fetch(`/api/admin/payments`,{
            method:"POST",
            body:JSON.stringify(form)
        })
        if(res.ok){
            toast("Invoice has beed update and payment created")
            location.reload()
        }else{
            toast("Unknown error occured!")
        }
    } catch (error) {
        toast("Unknown error occured!")
    }finally{
        setPaymentSubmittionLoading(false)
    }
  }

  return (
    <div className="md:p-6  space-y-6">
      <Button
        variant="outline"
        onClick={() => router.back()}
        className="flex gap-2"
      >
        <ArrowLeft size={16} /> Back
      </Button>

      <div className="grid md:grid-cols-3 gap-4 grid-cols-1">
       
      <div className="md:col-span-2">
        <InvoiceCard invoice={invoice}/>
      </div>
        <div>
          <Card>
            <CardHeader>
              <CardTitle>Actions</CardTitle>
              <CardDescription>
                Action you can perform across this invoice
              </CardDescription>
            </CardHeader>
            <CardContent>

              <div className="space-y-2 gap-4">
               {invoice.status !== 'paid' ? <div className="mb-5 space-x-2">
                 <Dialog>
                    <DialogTrigger asChild>
                        <Button variant={"outline"}>Mark as Paid</Button>
                    </DialogTrigger>
                   <DialogContent>
                     <DialogHeader>
                        <DialogTitle>Make payment completion </DialogTitle>
                        <DialogDescription>Make this paid when the user actually paid to you, this will add to you payments. To make sure it's accurate </DialogDescription>
                    </DialogHeader>
                    <Alert>
                        <AlertTitle className="flex items-center space-x-1">
                            <Sparkles className="w-4"/>
                            <h2 className="font-bold">Smarter</h2>
                        </AlertTitle>
                        <AlertDescription><p>The amount of Rs. <strong>{invoice.amount}</strong> has been paid by <strong>{invoice.student.firstName} {invoice.student.lastName}</strong> on <strong>{new Date().toLocaleString("en-US",{
                            month:"short",
                            day:"numeric",
                            year:"numeric"
                        })}</strong> as it will be added to your payments</p></AlertDescription>
                    </Alert>

                    <div className="grid grid-cols-2 gap-4">
                        <div className="space-y-2">
                            <Label className="font-semibold">Amount</Label>
                            <Input required type="text" value={invoice.amount}  onChange={(value)=>setForm({...form,amount:Number.parseInt(value.currentTarget.value)})} />
                        </div>
                        <div className="space-y-2">
                            <Label className="font-semibold">Payment method</Label>
                            <Select value={form.paymentMethod} onValueChange={(value)=> setForm({...form,paymentMethod:value})} required >
                                <SelectTrigger>
                                    <SelectValue placeholder="Select payment method"/>
                                </SelectTrigger>
                                <SelectContent className="min-x-[200px]">
                                    <SelectItem value="cash">Cash</SelectItem>
                                    <SelectItem value="bank_transfer">Bank transfer</SelectItem>
                                    <SelectItem value="online">Online</SelectItem>
                                    <SelectItem value="cheque">Cheque</SelectItem>
                                </SelectContent>
                            </Select>
                        </div>
                        <div className="space-y-2">
                            <Label className="font-semibold">Receipt number</Label>
                            <Input type="text"   onChange={(value)=>setForm({...form,receiptNumber:value.currentTarget.value})} placeholder="(optional) Payment receipt number" />
                        </div>
                        <div className="space-y-2">
                            <Label className="font-semibold">Notes</Label>
                            <Input type="text" onChange={(value)=>setForm({...form,notes:value.currentTarget.value})}  placeholder="(optional) Notes about payments" />
                        </div>
                    </div>
                   {paymentSubmittionLoading? 
                   <Button variant={"outline"} disabled>Processing...</Button>: 
                   <Button onClick={handlePaymentUpdation} className="bg-green-500 text-white hover:bg-green-600 cursor-pointer">Mark Paid</Button>}
                   </DialogContent>
                 </Dialog>
                {paymentSubmittionLoading?<Button variant={"outline"}>Processing...</Button>:<Button variant={"destructive"} onClick={()=>{
                    setForm({...form,status:"cancelled"})
                    handlePaymentUpdation()
                }} >Mark as Canceled</Button>}
               </div>:""}
               <Separator/>
                
                <h2 className="text-base font-bold">Other actions</h2>
                <button
                  onClick={handleDownloadInvoice}
                  className="w-full flex items-center cursor-pointer justify-center gap-2 bg-accent text-primary font-semibold py-2 rounded-lg hover:bg-accent/90 transition-colors"
                >
                  <Download className="w-4 h-4" />
                  Download Invoice
                </button>
                <button
                  onClick={handlePrint}
                  className="w-full flex items-center cursor-pointer justify-center gap-2 bg-primary text-primary-foreground font-semibold py-2 rounded-lg "
                >
                  <PrinterIcon className="w-4 h-4" />
                  Print Invoice
                </button>
                <button
                  onClick={() =>
                    location.assign(`/admin/students/${invoice.student.id}`)
                  }
                  className="w-full flex items-center bg-secondary cursor-pointer justify-center gap-2  font-semibold py-2 rounded-lg "
                >
                  <User className="w-4 h-4" />
                  View Student details
                </button>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>
    </div>
  );
}
